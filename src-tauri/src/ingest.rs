/// Load the ingest cache for a mods directory if it exists.
fn load_ingest_cache(mods_dir: &Path) -> Option<IngestCache> {
    let cache_path = cache_path(mods_dir);
    if !cache_path.exists() {
        return None;
    }
    let data = fs::read_to_string(&cache_path).ok()?;
    serde_json::from_str::<IngestCache>(&data).ok()
}

/// Extract a texture from its source (JAR archive or filesystem path) and
/// return it as a base64 PNG data URL.
fn texture_data_url_for_entry(entry: &TextureEntry) -> Option<String> {
    if entry.file_path.ends_with(".jar") || entry.file_path.contains(".jar!") {
        let jar_path = Path::new(&entry.file_path);
        let file = fs::File::open(jar_path).ok()?;
        let mut archive = ZipArchive::new(file).ok()?;
        let texture_path = entry.path.replace('\\', "/");
        let mut zip_entry = archive.by_name(&texture_path).ok()?;
        let mut buf = Vec::new();
        zip_entry.read_to_end(&mut buf).ok()?;
        if buf.is_empty() {
            return None;
        }
        Some(format!("data:image/png;base64,{}", STANDARD.encode(&buf)))
    } else {
        let buf = fs::read(&entry.file_path).ok()?;
        if buf.is_empty() {
            return None;
        }
        Some(format!("data:image/png;base64,{}", STANDARD.encode(&buf)))
    }
}

/// Resolve a texture key to a data URL from the ingest cache entries.
fn texture_data_url_for_key(cache: &IngestCache, texture_key: &str) -> Option<String> {
    let entry = cache.textures.iter().find(|t| {
        t.raw_key == texture_key || t.canonical_key == texture_key || t.clean_key == texture_key
    })?;
    texture_data_url_for_entry(entry)
}

/// Fallback: look up a texture key in `kubejs/assets` on the filesystem.
fn fallback_kubejs_texture(texture_key: &str, instance_path: &Path) -> Option<String> {
    let kubejs_assets_dir = instance_path.join("kubejs").join("assets");
    if !kubejs_assets_dir.exists() {
        return None;
    }
    let texture_path = texture_key.replace(':', "/").replace("textures/", "");
    let possible_paths = vec![
        kubejs_assets_dir.join(&texture_path),
        kubejs_assets_dir.join(texture_path.strip_prefix("textures/").unwrap_or(&texture_path)),
    ];

    for path in possible_paths {
        if path.exists() {
            if let Ok(buf) = fs::read(&path) {
                if !buf.is_empty() {
                    return Some(format!("data:image/png;base64,{}", STANDARD.encode(&buf)));
                }
            }
        }
    }
    None
}

/// Serve a texture file on-demand by key.
/// Extracts the texture from the JAR file or reads from filesystem.
#[tauri::command]
pub async fn get_texture_file(texture_key: String, instance_path: String) -> Result<String, String> {
    let instance_path = Path::new(&instance_path);
    if let Some(url) = load_ingest_cache(&instance_path.join("mods"))
        .and_then(|c| texture_data_url_for_key(&c, &texture_key))
    {
        return Ok(url);
    }
    if let Some(url) = fallback_kubejs_texture(&texture_key, instance_path) {
        return Ok(url);
    }
    Err("Texture not found".to_string())
}

/// Batch variant of `get_texture_file`: resolve many texture keys in a single
/// IPC round-trip. Returns a map of key → data URL (or `None` when a texture
/// could not be resolved).
#[tauri::command]
pub async fn get_texture_files(
    texture_keys: Vec<String>,
    instance_path: String,
) -> HashMap<String, Option<String>> {
    let instance_path = Path::new(&instance_path);
    let cache = load_ingest_cache(&instance_path.join("mods"));
    let mut out: HashMap<String, Option<String>> = HashMap::new();
    for key in texture_keys {
        let url = cache
            .as_ref()
            .and_then(|c| texture_data_url_for_key(c, &key))
            .or_else(|| fallback_kubejs_texture(&key, instance_path));
        out.insert(key, url);
    }
    out
}

